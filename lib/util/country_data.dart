String countryName(String countryCode, String languageCode) {
  final code = countryCode.toUpperCase();

  return countryNames[languageCode]?[code] ?? countryNames['en']![code] ?? code;
}

String countryFlag(String countryCode) =>
    String.fromCharCodes(countryCode.toUpperCase().codeUnits.map((unit) => unit - 0x41 + 0x1F1E6));
